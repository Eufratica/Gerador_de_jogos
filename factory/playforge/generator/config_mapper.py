"""Mapeamento deterministico GameSpecification -> Config/Projeto Godot 4.x."""
from __future__ import annotations

import math
import re
from typing import Any

from factory.playforge.generator.schemas import GeneratorError

_RESOLUTION_RE = re.compile(r"^\s*(\d+)\s*x\s*(\d+)\s*$")


def _gd_escape(value: str) -> str:
    """Escapa string Python para uso seguro dentro de literal GDScript entre aspas duplas."""
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "")
        .replace("\n", "\\n")
    )


def _ini_quote(value: str) -> str:
    """Formata string segura para valor entre aspas em project.godot."""
    cleaned = value.replace("\r", " ").replace("\n", " ").replace('"', "'").strip()
    return f'"{cleaned}"'


def _parse_resolution(raw_res: Any) -> tuple[int, int]:
    if not isinstance(raw_res, str):
        raise GeneratorError(f"ui_ux.resolution invalida: esperado 'WIDTHxHEIGHT', recebido {raw_res!r}.")
    match = _RESOLUTION_RE.match(raw_res)
    if not match:
        raise GeneratorError(f"Formato invalido em ui_ux.resolution: '{raw_res}'. Use '1920x1080'.")
    w, h = int(match.group(1)), int(match.group(2))
    if w <= 0 or h <= 0:
        raise GeneratorError(f"Dimensoes invalidas em ui_ux.resolution: {w}x{h}.")
    return w, h


def render_project_godot(
    base_project_godot: str,
    spec: dict[str, Any],
    *,
    template_id: str,
    template_version: str,
) -> str:
    """Parametriza project.godot a partir da GameSpecification mantendo estrutura valida."""
    width, height = _parse_resolution(spec["ui_ux"]["resolution"])
    orientation = 1 if spec["ui_ux"]["screen_orientation"] == "portrait" else 0
    app_name = _ini_quote(spec["name"])

    replacements = {
        "config/name=": f"config/name={app_name}",
        "window/size/viewport_width=": f"window/size/viewport_width={width}",
        "window/size/viewport_height=": f"window/size/viewport_height={height}",
        "window/handheld/orientation=": f"window/handheld/orientation={orientation}",
    }

    lines = base_project_godot.splitlines()
    out_lines: list[str] = [
        f"; Generated by PlayForge Factory (Fase 5) | game_id={spec['game_id']} | "
        f"spec={spec['spec_id']}@{spec['version']} | template={template_id}@{template_version}",
    ]
    seen_keys: set[str] = set()
    for line in lines:
        if line.startswith("; PlayForge Factory Template:"):
            out_lines.append(line)
            continue
        replaced = False
        for prefix, new_line in replacements.items():
            if line.startswith(prefix):
                out_lines.append(new_line)
                seen_keys.add(prefix)
                replaced = True
                break
        if not replaced:
            out_lines.append(line)

    missing = set(replacements.keys()) - seen_keys
    if missing:
        raise GeneratorError(
            f"Template base project.godot nao contem chaves esperadas: {sorted(missing)}."
        )

    return "\n".join(out_lines) + "\n"


def _worst_case_campaign_damage(
    hero_attack: float,
    raw_rooms: list[tuple[float, float]],
    scale: float,
) -> float:
    """Calcula dano maximo sem criticos que o heroi receberia em toda a campanha."""
    total_dmg = 0.0
    for base_hp, base_atk in raw_rooms:
        hp = max(1.0, round(base_hp * scale, 2))
        atk = max(0.0, round(base_atk * scale, 2))
        hits = max(1, math.ceil(hp / hero_attack))
        total_dmg += (hits - 1) * atk
    return total_dmg


def map_spec_to_runtime_config(spec: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    """Converte GameSpecification em config/template_defaults.json + metadados de balanceamento."""
    characters = spec["characters"]
    player = next((c for c in characters if c.get("role") == "player"), characters[0])
    stats = player["stats"]

    hero_hp = float(stats["base_health"])
    hero_atk = float(stats["base_attack"])
    move_speed = float(stats.get("speed", 260.0))
    if hero_hp <= 0.0 or hero_atk <= 0.0 or move_speed <= 0.0:
        raise GeneratorError("Atributos do heroi na spec devem ser estritamente positivos.")

    enemies = spec["enemies"]
    minion = next((e for e in enemies if e.get("type") == "minion"), enemies[0])
    boss = next((e for e in enemies if e.get("type") == "boss"), enemies[-1])

    scaling = float(spec["difficulty"]["base_scaling"])
    boss_mult = float(spec["difficulty"].get("boss_multiplier", 1.5))

    spec_worlds = spec["worlds_and_levels"]["worlds"]
    total_rooms = sum(len(w["rooms"]) for w in spec_worlds)
    if total_rooms <= 0:
        raise GeneratorError("GameSpecification nao possui salas para gerar.")

    # Monta encontros brutos por sala antes da normalizacao deterministica de jogabilidade
    raw_encounters: list[dict[str, Any]] = []
    global_idx = 0
    for world in spec_worlds:
        for room in world["rooms"]:
            is_last_room = (global_idx == total_rooms - 1) and total_rooms > 1
            tpl_enemy = boss if is_last_room else minion
            factor = math.pow(scaling, global_idx)
            if is_last_room and tpl_enemy is not boss:
                factor *= boss_mult
            raw_encounters.append(
                {
                    "world_id": world["world_id"],
                    "room": room,
                    "enemy_name": str(tpl_enemy["name"]),
                    "raw_hp": float(tpl_enemy["base_health"]) * factor,
                    "raw_atk": float(tpl_enemy["base_damage"]) * factor,
                    "reward_gold": round(25.0 * (2.0 if is_last_room else 1.0) * factor, 2),
                }
            )
            global_idx += 1

    hp_atk_pairs = [(enc["raw_hp"], enc["raw_atk"]) for enc in raw_encounters]
    max_safe_damage = hero_hp * 0.75
    raw_damage = _worst_case_campaign_damage(hero_atk, hp_atk_pairs, scale=1.0)

    scale_factor = 1.0
    normalized = False
    if raw_damage > max_safe_damage:
        normalized = True
        lo, hi = 0.001, 1.0
        for _ in range(32):
            mid = (lo + hi) * 0.5
            if _worst_case_campaign_damage(hero_atk, hp_atk_pairs, scale=mid) <= max_safe_damage:
                lo = mid
            else:
                hi = mid
        scale_factor = math.floor(lo * 10000.0) / 10000.0
        while scale_factor > 0.0 and _worst_case_campaign_damage(hero_atk, hp_atk_pairs, scale=scale_factor) > max_safe_damage:
            scale_factor = round(scale_factor * 0.95, 4)

    eff_damage = _worst_case_campaign_damage(hero_atk, hp_atk_pairs, scale=scale_factor)
    if eff_damage > max_safe_damage or eff_damage >= hero_hp:
        raise GeneratorError(
            "Nao foi possivel garantir campanha jogavel sem soft-lock a partir da spec fornecida."
        )

    # Reconstroi worlds respeitando exatamente os IDs e nomes da GameSpecification
    enc_idx = 0
    out_worlds: list[dict[str, Any]] = []
    for world in spec_worlds:
        out_rooms: list[dict[str, Any]] = []
        rooms_list = world["rooms"]
        for r_idx, room in enumerate(rooms_list):
            enc = raw_encounters[enc_idx]
            enc_idx += 1
            next_id = ""
            conns = room.get("connections", [])
            if conns:
                next_id = str(conns[0].get("target_room_id", ""))
            elif r_idx + 1 < len(rooms_list):
                next_id = str(rooms_list[r_idx + 1]["room_id"])

            out_rooms.append(
                {
                    "room_id": str(room["room_id"]),
                    "name": str(room["name"]),
                    "enemy_name": enc["enemy_name"],
                    "enemy_hp": max(1.0, round(enc["raw_hp"] * scale_factor, 2)),
                    "enemy_attack": max(0.0, round(enc["raw_atk"] * scale_factor, 2)),
                    "reward_gold": enc["reward_gold"],
                    "next_room_id": next_id,
                }
            )
        out_worlds.append(
            {
                "world_id": str(world["world_id"]),
                "name": str(world["name"]),
                "rooms": out_rooms,
            }
        )

    runtime_cfg = {
        "schema_version": 1,
        "game_id": spec["game_id"],
        "game_name": spec["name"],
        "spec_id": spec["spec_id"],
        "spec_version": spec["version"],
        "genre": spec["genre"],
        "hero": {
            "name": str(player["name"]),
            "base_hp": round(hero_hp, 2),
            "base_attack": round(hero_atk, 2),
            "move_speed": round(move_speed, 2),
        },
        "worlds": out_worlds,
    }
    balance_info = {
        "normalized": normalized,
        "scale_factor": scale_factor,
        "raw_worst_case_damage": round(raw_damage, 2),
        "effective_worst_case_damage": round(eff_damage, 2),
        "hero_max_hp": round(hero_hp, 2),
        "total_worlds": len(out_worlds),
        "total_rooms": total_rooms,
    }
    return runtime_cfg, balance_info


def render_generated_verification_test(
    spec: dict[str, Any],
    runtime_cfg: dict[str, Any],
) -> str:
    """Gera o runner Godot CLI tests/unit/verify_generated_game.gd especifico do jogo gerado."""
    game_id = _gd_escape(spec["game_id"])
    game_name = _gd_escape(spec["name"])
    expected_worlds = len(runtime_cfg["worlds"])
    expected_rooms = sum(len(w["rooms"]) for w in runtime_cfg["worlds"])
    expected_min_gold = round(
        sum(float(room["reward_gold"]) for w in runtime_cfg["worlds"] for room in w["rooms"]),
        2,
    )

    return f'''extends SceneTree
## Verificacao headless gerada pela PlayForge Factory (Fase 5) para: {game_id}

const HarnessScript = preload("res://tests/unit/test_harness.gd")
const BigNumScript = preload("res://src/core/big_num.gd")
const SeededRngScript = preload("res://src/core/seeded_rng.gd")
const CoreScript = preload("res://src/core/game_loop_core.gd")
const SaveStoreScript = preload("res://src/engine/local_checkpoint_store.gd")
const MainScene = preload("res://src/engine/main.tscn")

const EXPECTED_GAME_ID: String = "{game_id}"
const EXPECTED_GAME_NAME: String = "{game_name}"
const EXPECTED_WORLDS: int = {expected_worlds}
const EXPECTED_TOTAL_ROOMS: int = {expected_rooms}
const EXPECTED_MIN_GOLD: float = {expected_min_gold}


func _initialize() -> void:
\tvar t0_usec: int = Time.get_ticks_usec()
\tvar t := HarnessScript.new("GeneratedGame:" + EXPECTED_GAME_ID)

\t# 1. Invariantes puros herdados (BigNum, SeededRng e fail-closed JSON)
\tvar a: RefCounted = BigNumScript.from_float(100.0)
\tvar b: RefCounted = BigNumScript.from_float(50.0)
\tt.assert_eq(int(round(a.add(b).to_approx_float())), 150, "BigNum add deterministic")
\tvar rng1 := SeededRngScript.new(42)
\tvar rng2 := SeededRngScript.new(42)
\tt.assert_eq(rng1.next_u32(), rng2.next_u32(), "SeededRng deterministic")
\tvar bad_core: RefCounted = CoreScript.parse_and_create("{{invalid json")
\tt.assert_false(bool(bad_core.get("valid")), "Invalid JSON rejected fail-closed")

\t# 2. Config parametrizada da GameSpecification
\tvar cfg_exists: bool = FileAccess.file_exists("res://config/template_defaults.json")
\tt.assert_true(cfg_exists, "Config template_defaults.json exists")
\tvar cfg_text: String = FileAccess.get_file_as_string("res://config/template_defaults.json")

\tvar parsed = JSON.parse_string(cfg_text)
\tt.assert_true(parsed is Dictionary, "Config parses as Dictionary")
\tif parsed is Dictionary:
\t\tt.assert_eq(String(parsed.get("game_id", "")), EXPECTED_GAME_ID, "Config game_id matches project_id")
\t\tt.assert_eq(String(parsed.get("game_name", "")), EXPECTED_GAME_NAME, "Config game_name matches spec")
\t\tvar ws: Array = parsed.get("worlds", [])
\t\tt.assert_eq(ws.size(), EXPECTED_WORLDS, "Config world count matches spec")
\t\tvar room_sum: int = 0
\t\tfor w in ws:
\t\t\troom_sum += (w.get("rooms", []) as Array).size()
\t\tt.assert_eq(room_sum, EXPECTED_TOTAL_ROOMS, "Config room count matches spec")

\t# 3. Simulacao deterministica completa de campanha
\tvar core: RefCounted = CoreScript.parse_and_create(cfg_text, 202605)
\tt.assert_true(bool(core.get("valid")), "GameLoopCore boots generated config")

\tvar steps: int = 0
\twhile not bool(core.get("campaign_cleared")) and not bool(core.get("defeated")) and steps < 500:
\t\tcore.step(0.1, 1.0, true)
\t\tsteps += 1
\tt.assert_true(bool(core.get("campaign_cleared")), "Generated campaign clears without softlock")
\tt.assert_false(bool(core.get("defeated")), "Hero survives generated campaign")
\tt.assert_true(core.get("gold").to_approx_float() + 0.01 >= EXPECTED_MIN_GOLD, "Economy reward matches rooms")

\t# 4. Persistencia fail-closed + roundtrip
\tt.assert_true(SaveStoreScript.load_snapshot("res://config/nonexistent.json").is_empty(), "Missing save returns empty")
\tvar snap: Dictionary = core.export_checkpoint_snapshot()
\tvar save_path: String = "user://generated_verify_" + EXPECTED_GAME_ID + ".json"
\tt.assert_true(SaveStoreScript.save_snapshot(snap, save_path), "Checkpoint save succeeds")
\tvar loaded: Dictionary = SaveStoreScript.load_snapshot(save_path)
\tt.assert_eq(String(loaded.get("game_id", "")), EXPECTED_GAME_ID, "Checkpoint load preserves game_id")
\tSaveStoreScript.clear_save(save_path)

\t# 5. Boot real da cena Main.tscn
\tvar main_inst: Control = MainScene.instantiate()
\tt.assert_true(main_inst != null, "MainScene instantiates cleanly")
\troot.add_child(main_inst)
\tawait process_frame
\tt.assert_true(main_inst.is_boot_valid(), "MainScene boot gate valid")
\tmain_inst.queue_free()
\tawait process_frame

\tvar elapsed_ms: float = float(Time.get_ticks_usec() - t0_usec) / 1000.0
\tprint("=== PLAYFORGE GENERATED GAME VERIFICATION (%s) ===" % EXPECTED_GAME_ID)
\tprint("Assertions: %d | Failed: %d | Elapsed: %.2f ms" % [t.total_assertions, t.failed_assertions, elapsed_ms])
\tfor err in t.failures:
\t\tprinterr(err)

\tif t.failed_assertions > 0 or elapsed_ms >= 1000.0:
\t\tquit(1)
\t\treturn
\tquit(0)
'''
